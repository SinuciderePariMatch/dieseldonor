@app.route("/api/products")
def products_api():
    with get_db() as conn:
        products = conn.execute(
            "SELECT * FROM products ORDER BY id DESC"
        ).fetchall()

    return jsonify(products)


# Список моделей двигателей
@app.route("/api/engine-models")
def engine_models_api():
    with get_db() as conn:
        models = conn.execute("""
            SELECT *
            FROM engine_models
            WHERE is_active = TRUE
            ORDER BY make, model, chassis
        """).fetchall()

    return jsonify(models)


# Список схем выбранного двигателя
@app.route("/api/engine-models/<int:model_id>/diagrams")
def engine_diagrams_api(model_id):
    with get_db() as conn:
        diagrams = conn.execute("""
            SELECT *
            FROM engine_diagrams
            WHERE model_id = %s
              AND is_active = TRUE
            ORDER BY sort_order, title
        """, (model_id,)).fetchall()

    return jsonify(diagrams)


# Позиции на конкретной схеме
@app.route("/api/diagrams/<int:diagram_id>/positions")
def diagram_positions_api(diagram_id):
    with get_db() as conn:
        positions = conn.execute("""
            SELECT
                dp.*,
                COALESCE(
                    json_agg(
                        json_build_object(
                            'id', p.id,
                            'name', p.name,
                            'article', p.article,
                            'availability', p.availability
                        )
                    ) FILTER (WHERE p.id IS NOT NULL),
                    '[]'
                ) AS products
            FROM diagram_positions dp
            LEFT JOIN diagram_product_links dpl
                ON dpl.position_id = dp.id
            LEFT JOIN products p
                ON p.id = dpl.product_id
            WHERE dp.diagram_id = %s
            GROUP BY dp.id
            ORDER BY dp.sort_order, dp.position_number
        """, (diagram_id,)).fetchall()

    return jsonify(positions)


# Авторизация
@app.route("/admin/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")

        with get_db() as conn:
            user = conn.execute(
                "SELECT * FROM admins WHERE username = %s",
                (username,)
            ).fetchone()

        if user and check_password_hash(
            user["password_hash"], password
        ):
            session["admin_id"] = user["id"]
            return redirect(url_for("admin"))

        flash("Неверный логин или пароль")

    return render_template("login.html")


@app.route("/admin/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


# Админка
@app.route("/admin")
@admin_required
def admin():
    with get_db() as conn:
        products = conn.execute(
            "SELECT * FROM products ORDER BY id DESC"
        ).fetchall()

    return render_template("admin.html", products=products)


@app.route("/admin/add", methods=["POST"])
@admin_required
def add_product():
    name = request.form.get("name", "").strip()

    if not name:
        flash("Укажи название товара")
        return redirect(url_for("admin"))

    values = (
        name,
        request.form.get("category", "Другие комплектующие"),
        request.form.get("article", ""),
        request.form.get("description", ""),
        request.form.get("photo_url", ""),
        request.form.get("availability", "В наличии")
    )

    with get_db() as conn:
        conn.execute("""
            INSERT INTO products
            (name, category, article, description, photo_url, availability)
            VALUES (%s, %s, %s, %s, %s, %s)
        """, values)

    flash("Товар добавлен")
    return redirect(url_for("admin"))


@app.route("/admin/delete/<int:product_id>", methods=["POST"])
@admin_required
def delete_product(product_id):
    with get_db() as conn:
        conn.execute(
            "DELETE FROM products WHERE id = %s",
            (product_id,)
        )

    flash("Товар удалён")
    return redirect(url_for("admin"))


init_db()


if __name__ == "__main__":
    app.run(
        host="0.0.0.0",
        port=int(os.environ.get("PORT", 5000))
    )
