@app.route("/admin/chats")
@admin_required
def admin_chats():
    try:
        with get_db() as conn:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS chat_messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    session_id TEXT NOT NULL, sender TEXT NOT NULL, message TEXT NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
            chats = conn.execute("""
                SELECT session_id, MAX(created_at) as last_msg_time, COUNT(*) as msg_count,
                (SELECT message FROM chat_messages cm2 WHERE cm2.session_id = cm1.session_id ORDER BY cm2.created_at DESC LIMIT 1) as last_message,
                (SELECT sender FROM chat_messages cm3 WHERE cm3.session_id = cm1.session_id ORDER BY cm3.created_at DESC LIMIT 1) as last_sender
                FROM chat_messages cm1 GROUP BY session_id ORDER BY last_msg_time DESC
            """).fetchall()
    except Exception as e:
        print(f"ERROR loading chats: {e}"); chats = []
    return render_template("admin_chats.html", chats=chats)


