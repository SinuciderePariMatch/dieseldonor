@app.route("/cart")
def cart():
    cart_items = session.get("cart", [])
    products = []
    total_price = 0
    
    if cart_items:
        ids = [item["id"] for item in cart_items]
        placeholders = ",".join(["%s"] * len(ids))
        
        with get_db() as conn:
            rows = conn.execute(
                f"SELECT * FROM products WHERE id IN ({placeholders})", ids
            ).fetchall()
            
        for row in rows:
            qty = next((i["qty"] for i in cart_items if i["id"] == row["id"]), 1)
            products.append({**row, "qty": qty})
            total_price += (row["price"] or 0) * qty
            
    return render_template("cart.html", products=products, total_price=total_price)


@app.route("/cart/add", methods=["POST"])
def add_to_cart():
    product_id = int(request.form.get("product_id"))
    qty = int(request.form.get("qty", 1))
    
    cart = session.get("cart", [])
    existing = next((i for i in cart if i["id"] == product_id), None)
    
    if existing:
        existing["qty"] += qty
    else:
        cart.append({"id": product_id, "qty": qty})
        
    session["cart"] = cart
    session.modified = True
    
    if request.headers.get("X-Requested-With") == "XMLHttpRequest":
        return jsonify({"status": "ok", "count": sum(i["qty"] for i in cart)})
        
    return redirect(url_for("cart"))


@app.route("/cart/remove", methods=["POST"])
def remove_from_cart():
    product_id = int(request.form.get("product_id"))
    cart = session.get("cart", [])
    cart = [i for i in cart if i["id"] != product_id]
    session["cart"] = cart
    session.modified = True
    return redirect(url_for("cart"))


@app.route("/cart/clear", methods=["POST"])
def clear_cart():
    session["cart"] = []
    session.modified = True
    return redirect(url_for("cart"))


