import os
from functools import wraps
import psycopg
from psycopg.rows import dict_row
from flask import Flask, render_template, request, redirect, url_for, session, flash, jsonify
from werkzeug.security import generate_password_hash, check_password_hash

app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "change-this-secret-in-production")

DATABASE_URL = os.environ.get("DATABASE_URL")
if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is not configured")

# Render иногда отдает postgres://, а psycopg требует postgresql://
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)


def get_db():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_db():
    """Создает таблицы при первом запуске"""
    with get_db() as conn:
        # Таблица товаров
        conn.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                description TEXT DEFAULT '',
                price INTEGER DEFAULT 0,
                category TEXT DEFAULT 'Другие комплектующие',
                brand TEXT DEFAULT '',
                model TEXT DEFAULT '',
                engine TEXT DEFAULT '',
                body_type TEXT DEFAULT '',
                part_number TEXT DEFAULT '',
                cross_numbers TEXT DEFAULT '',
                images TEXT DEFAULT '',
                quantity_available INTEGER DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        
        # Администраторы
        conn.execute("""
            CREATE TABLE IF NOT EXISTS admins (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL
            )
        """)

        # Создаем админа из переменных окружения
        username = os.environ.get("ADMIN_USERNAME")
        password = os.environ.get("ADMIN_PASSWORD")
        if username and password:
            existing = conn.execute(
                "SELECT id FROM admins WHERE username = %s", (username,)
            ).fetchone()
            if not existing:
                conn.execute(
                    "INSERT INTO admins (username, password_hash) VALUES (%s, %s)",
                    (username, generate_password_hash(password))
                )
        conn.commit()


