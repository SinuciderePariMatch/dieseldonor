import os
from functools import wraps
import psycopg
from psycopg.rows import dict_row
from flask import Flask, render_template, request, redirect, url_for, session, flash, jsonify
from werkzeug.security import generate_password_hash, check_password_hash

app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "change-this-secret-in-production")

DATABASE_URL = os.environ.get("DATABASE_URL")
if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is not configured")

# Render иногда отдает postgres://, а psycopg требует postgresql://
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)


def get_db():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_db():
    """Создает таблицы, если их нет, и добавляет тестовые данные"""
    with get_db() as conn:
        # Таблица товаров (расширенная под CSV)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                description TEXT DEFAULT '',
                price INTEGER DEFAULT 0,
                category TEXT DEFAULT 'Другие комплектующие',
                brand TEXT DEFAULT '',
                model TEXT DEFAULT '',
                engine TEXT DEFAULT '',
                body_type TEXT DEFAULT '',
                part_number TEXT DEFAULT '',
                cross_numbers TEXT DEFAULT '',
                images TEXT DEFAULT '',
                quantity_available INTEGER DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Администраторы
        conn.execute("""
            CREATE TABLE IF NOT EXISTS admins (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL
            )
        """)

        # Интерактивные схемы (оставляем для будущего функционала)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS engine_models (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                make TEXT NOT NULL, model TEXT NOT NULL, 
                chassis TEXT NOT NULL, engine TEXT NOT NULL,
                UNIQUE (make, model, chassis, engine)
            )
        """)
        
        conn.execute("""
            CREATE TABLE IF NOT EXISTS engine_diagrams (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                model_id BIGINT REFERENCES engine_models(id) ON DELETE CASCADE,
                system_name TEXT NOT NULL, title TEXT NOT NULL,
                image_url TEXT DEFAULT '', is_active BOOLEAN DEFAULT TRUE
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS diagram_positions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                diagram_id BIGINT REFERENCES engine_diagrams(id) ON DELETE CASCADE,
                position_number TEXT NOT NULL, name TEXT DEFAULT '',
                x_percent NUMERIC(6,2) NOT NULL, y_percent NUMERIC(6,2) NOT NULL,
                UNIQUE (diagram_id, position_number)
            )
        """)

        # Создаем админа из переменных окружения, если его нет
        username = os.environ.get("ADMIN_USERNAME")
        password = os.environ.get("ADMIN_PASSWORD")
        if username and password:
            existing = conn.execute(
                "SELECT id FROM admins WHERE username = %s", (username,)
            ).fetchone()
            if not existing:
                conn.execute(
                    "INSERT INTO admins (username, password_hash) VALUES (%s, %s)",
                    (username, generate_password_hash(password))
                )
        conn.commit()


def admin_required(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        if not session.get("admin_id"):
            return redirect(url_for("login"))
        return func(*args, **kwargs)
    return wrapper


