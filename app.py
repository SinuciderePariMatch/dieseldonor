@app.route("/")
def home():
    """Главная страница с поиском и популярными товарами"""
    popular_products = []
    try:
        with get_db() as conn:
            # Берем 8 самых дорогих или новых товаров для витрины
            popular_products = conn.execute("""
                SELECT * FROM products 
                ORDER BY price DESC NULLS LAST, created_at DESC 
                LIMIT 8
            """).fetchall()
    except Exception as e:
        print(f"Error loading popular products: {e}")
        
    return render_template("index.html", popular_products=popular_products)


@app.route("/catalog")
def catalog():
    """Каталог с фильтрацией и поиском"""
    category = request.args.get('cat', '').strip()
    search = request.args.get('q', '').strip()
    
    products = []
    try:
        with get_db() as conn:
            query = "SELECT * FROM products WHERE 1=1"
            params = []
            
            if category:
                query += " AND category ILIKE %s"
                params.append(f"%{category}%")
                
            if search:
                # Ищем по названию, номеру детали и двигателю
                query += " AND (name ILIKE %s OR part_number ILIKE %s OR engine ILIKE %s)"
                t = f"%{search}%"
                params.extend([t, t, t])
                
            query += " ORDER BY created_at DESC"
            products = conn.execute(query, params).fetchall()
            
    except Exception as e:
        print(f"Error loading catalog: {e}")

    return render_template(
        "catalog.html", 
        products=products, 
        selected_category=category,
        search_query=search
    )


@app.route("/product/<int:product_id>")
def product_detail(product_id):
    """Страница отдельного товара с галереей"""
    product = None
    try:
        with get_db() as conn:
            product = conn.execute(
                "SELECT * FROM products WHERE id = %s", (product_id,)
            ).fetchone()
    except Exception as e:
        print(f"Error loading product: {e}")
        
    if not product:
        flash("Товар не найден")
        return redirect(url_for("home"))
        
    return render_template("product.html", product=product)


@app.route("/api/products")
def products_api():
    """API для живого поиска без перезагрузки страницы"""
    search = request.args.get('q', '').strip()
    category = request.args.get('cat', '').strip()
    
    with get_db() as conn:
        query = "SELECT id, name, price, images, category, brand, model FROM products WHERE 1=1"
        params = []
        
        if category:
            query += " AND category ILIKE %s"
            params.append(f"%{category}%")
        if search:
            query += " AND (name ILIKE %s OR part_number ILIKE %s)"
            t = f"%{search}%"
            params.extend([t, t])
            
        products = conn.execute(query + " LIMIT 50", params).fetchall()
        
    return jsonify(products)


