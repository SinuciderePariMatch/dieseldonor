
import os
from functools import wraps

import psycopg
from psycopg.rows import dict_row

from flask import (
    Flask, render_template, request, redirect,
    url_for, session, flash, jsonify
)
from werkzeug.security import generate_password_hash, check_password_hash


app = Flask(__name__)
app.secret_key = os.environ.get("SECRET_KEY", "change-this-secret")

DATABASE_URL = os.environ.get("DATABASE_URL")

if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is not configured")

if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace(
        "postgres://", "postgresql://", 1
    )


def get_db():
    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )


def init_db():
    with get_db() as conn:

        # Существующие таблицы товаров и администраторов
        conn.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                category TEXT DEFAULT 'Другие комплектующие',
                article TEXT DEFAULT '',
                description TEXT DEFAULT '',
                photo_url TEXT DEFAULT '',
                availability TEXT DEFAULT 'В наличии'
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS admins (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL
            )
        """)

        # Модели двигателей
        conn.execute("""
            CREATE TABLE IF NOT EXISTS engine_models (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                make TEXT NOT NULL,
                model TEXT NOT NULL,
                chassis TEXT NOT NULL,
                engine TEXT NOT NULL,
                year_from INTEGER,
                year_to INTEGER,
                is_active BOOLEAN DEFAULT TRUE,
                UNIQUE (make, model, chassis, engine)
            )
        """)

        # Заводские схемы узлов
        conn.execute("""
            CREATE TABLE IF NOT EXISTS engine_diagrams (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                model_id BIGINT NOT NULL
                    REFERENCES engine_models(id) ON DELETE CASCADE,
                system_name TEXT NOT NULL,
                title TEXT NOT NULL,
                diagram_code TEXT DEFAULT '',
                image_url TEXT DEFAULT '',
                year_from INTEGER,
                year_to INTEGER,
                notes TEXT DEFAULT '',
                sort_order INTEGER DEFAULT 0,
                is_active BOOLEAN DEFAULT FALSE
            )
        """)

        # Пронумерованные позиции на схемах
        conn.execute("""
            CREATE TABLE IF NOT EXISTS diagram_positions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                diagram_id BIGINT NOT NULL
                    REFERENCES engine_diagrams(id) ON DELETE CASCADE,
                position_number TEXT NOT NULL,
                name TEXT DEFAULT '',
                oem_number TEXT DEFAULT '',
                cross_numbers TEXT DEFAULT '',
                x_percent NUMERIC(6,2) NOT NULL
                    CHECK (x_percent >= 0 AND x_percent <= 100),
                y_percent NUMERIC(6,2) NOT NULL
                    CHECK (y_percent >= 0 AND y_percent <= 100),
                notes TEXT DEFAULT '',
                sort_order INTEGER DEFAULT 0,
                UNIQUE (diagram_id, position_number)
            )
        """)

        # Связь позиций схем с товарами DieselDonor
        conn.execute("""
            CREATE TABLE IF NOT EXISTS diagram_product_links (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                position_id BIGINT NOT NULL
                    REFERENCES diagram_positions(id) ON DELETE CASCADE,
                product_id BIGINT NOT NULL
                    REFERENCES products(id) ON DELETE CASCADE,
                UNIQUE (position_id, product_id)
            )
        """)

        # Индексы для быстрого поиска
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_engine_diagrams_model
            ON engine_diagrams(model_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_diagram_positions_diagram
            ON diagram_positions(diagram_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_diagram_positions_oem
            ON diagram_positions(oem_number)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_diagram_links_product
            ON diagram_product_links(product_id)
        """)

        # Добавляем нашу первую модель, если её ещё нет
        conn.execute("""
            INSERT INTO engine_models
                (make, model, chassis, engine, year_from, year_to)
            VALUES
                ('Toyota', 'Hiace', 'KZH106', '1KZ-TE', 1993, 2004)
            ON CONFLICT (make, model, chassis, engine)
            DO NOTHING
        """)

        # Создание администратора, если его ещё нет
        username = os.environ.get("ADMIN_USERNAME")
        password = os.environ.get("ADMIN_PASSWORD")

        if username and password:
            existing = conn.execute(
                "SELECT id FROM admins WHERE username = %s",
                (username,)
            ).fetchone()

            if not existing:
                conn.execute("""
                    INSERT INTO admins (username, password_hash)
                    VALUES (%s, %s)
                """, (
                    username,
                    generate_password_hash(password)
                ))


def admin_required(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        if not session.get("admin_id"):
            return redirect(url_for("login"))
        return func(*args, **kwargs)
    return wrapper


