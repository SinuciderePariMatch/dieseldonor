@app.route("/cart")
def cart():
    """Страница корзины"""
    cart_items = session.get("cart", [])
    products = []
    total_price = 0
    
    if cart_items:
        ids = [item["id"] for item in cart_items]
        placeholders = ",".join(["%s"] * len(ids))
        
        with get_db() as conn:
            rows = conn.execute(
                f"SELECT * FROM products WHERE id IN ({placeholders})", ids
            ).fetchall()
            
        # Сопоставляем товары с количеством в корзине
        for row in rows:
            qty = next((i["qty"] for i in cart_items if i["id"] == row["id"]), 1)
            products.append({**row, "qty": qty})
            total_price += (row["price"] or 0) * qty
            
    return render_template("cart.html", products=products, total_price=total_price)


@app.route("/cart/add", methods=["POST"])
def add_to_cart():
    """Добавление товара в корзину"""
    product_id = int(request.form.get("product_id"))
    qty = int(request.form.get("qty", 1))
    
    cart = session.get("cart", [])
    existing = next((i for i in cart if i["id"] == product_id), None)
    
    if existing:
        existing["qty"] += qty
    else:
        cart.append({"id": product_id, "qty": qty})
        
    session["cart"] = cart
    session.modified = True
    
    # Возвращаем JSON для AJAX или редирект
    if request.headers.get("X-Requested-With") == "XMLHttpRequest":
        return jsonify({"status": "ok", "count": sum(i["qty"] for i in cart)})
        
    return redirect(url_for("cart"))


@app.route("/cart/remove", methods=["POST"])
def remove_from_cart():
    """Удаление из корзины"""
    product_id = int(request.form.get("product_id"))
    cart = session.get("cart", [])
    cart = [i for i in cart if i["id"] != product_id]
    session["cart"] = cart
    session.modified = True
    return redirect(url_for("cart"))


@app.route("/cart/clear", methods=["POST"])
def clear_cart():
    session["cart"] = []
    session.modified = True
    return redirect(url_for("cart"))


# --- АДМИНКА И АВТОРИЗАЦИЯ ---

def admin_required(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        if not session.get("admin_id"):
            return redirect(url_for("login"))
        return func(*args, **kwargs)
    return wrapper


@app.route("/admin/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        
        with get_db() as conn:
            user = conn.execute(
                "SELECT * FROM admins WHERE username = %s", (username,)
            ).fetchone()
            
        if user and check_password_hash(user["password_hash"], password):
            session["admin_id"] = user["id"]
            return redirect(url_for("admin"))
        flash("Неверный логин или пароль")
        
    return render_template("login.html")


@app.route("/admin/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


@app.route("/admin")
@admin_required
def admin():
    with get_db() as conn:
        products = conn.execute("SELECT * FROM products ORDER BY id DESC").fetchall()
    return render_template("admin.html", products=products)


@app.route("/admin/add", methods=["POST"])
@admin_required
def add_product():
    name = request.form.get("name", "").strip()
    if not name:
        flash("Укажи название товара")
        return redirect(url_for("admin"))
        
    values = (
        name,
        request.form.get("description", ""),
        int(request.form.get("price", 0) or 0),
        request.form.get("category", "Другие комплектующие"),
        request.form.get("brand", ""),
        request.form.get("model", ""),
        request.form.get("engine", ""),
        request.form.get("part_number", ""),
        request.form.get("images", "")
    )
    
    with get_db() as conn:
        conn.execute("""
            INSERT INTO products 
            (name, description, price, category, brand, model, engine, part_number, images)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        """, values)
        conn.commit()
        
    flash("Товар добавлен")
    return redirect(url_for("admin"))


@app.route("/admin/delete/<int:product_id>", methods=["POST"])
@admin_required
def delete_product(product_id):
    with get_db() as conn:
        conn.execute("DELETE FROM products WHERE id = %s", (product_id,))
        conn.commit()
    flash("Товар удалён")
    return redirect(url_for("admin"))


