@app.route("/admin/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        username = request.form.get("username", "").strip()
        password = request.form.get("password", "")
        
        with get_db() as conn:
            user = conn.execute(
                "SELECT * FROM admins WHERE username = %s", (username,)
            ).fetchone()
            
        if user and check_password_hash(user["password_hash"], password):
            session["admin_id"] = user["id"]
            return redirect(url_for("admin"))
        flash("Неверный логин или пароль")
        
    return render_template("login.html")


@app.route("/admin/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


@app.route("/admin")
@admin_required
def admin():
    with get_db() as conn:
        products = conn.execute("SELECT * FROM products ORDER BY id DESC").fetchall()
    return render_template("admin.html", products=products)


@app.route("/admin/add", methods=["POST"])
@admin_required
def add_product():
    name = request.form.get("name", "").strip()
    if not name:
        flash("Укажи название товара")
        return redirect(url_for("admin"))
        
    values = (
        name,
        request.form.get("description", ""),
        int(request.form.get("price", 0) or 0),
        request.form.get("category", "Другие комплектующие"),
        request.form.get("brand", ""),
        request.form.get("model", ""),
        request.form.get("engine", ""),
        request.form.get("part_number", ""),
        request.form.get("images", "")
    )
    
    with get_db() as conn:
        conn.execute("""
            INSERT INTO products 
            (name, description, price, category, brand, model, engine, part_number, images)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        """, values)
        conn.commit()
        
    flash("Товар добавлен")
    return redirect(url_for("admin"))


@app.route("/admin/delete/<int:product_id>", methods=["POST"])
@admin_required
def delete_product(product_id):
    with get_db() as conn:
        conn.execute("DELETE FROM products WHERE id = %s", (product_id,))
        conn.commit()
    flash("Товар удалён")
    return redirect(url_for("admin"))


# Инициализация БД при старте
init_db()

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", 5000)))