@app.route("/catalog")
def catalog():
    category = request.args.get('cat', '').strip()
    search = request.args.get('q', '').strip()
    products = []
    try:
        with get_db() as conn:
            query = "SELECT * FROM products WHERE 1=1"
            params = []
            if category:
                query += " AND category ILIKE %s"; params.append(f"%{category}%")
            if search:
                query += " AND (name ILIKE %s OR part_number ILIKE %s OR engine ILIKE %s)"
                t = f"%{search}%"; params.extend([t, t, t])
            query += " ORDER BY created_at DESC"
            products = conn.execute(query, params).fetchall()
    except Exception as e:
        print(f"Error loading catalog: {e}")
    return render_template("catalog.html", products=products, selected_category=category, search_query=search)


