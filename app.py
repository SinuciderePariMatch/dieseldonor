DATABASE_URL = os.environ.get("DATABASE_URL")
if not DATABASE_URL:
    raise RuntimeError("DATABASE_URL is not configured")

if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)


def get_db():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


# --- ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ И ДЕКОРАТОРЫ ---

def admin_required(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        if not session.get("admin_id"):
            return redirect(url_for("login"))
        return func(*args, **kwargs)
    return wrapper


def init_db():
    with get_db() as conn:
        # Таблица товаров
        conn.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL, description TEXT DEFAULT '', price INTEGER DEFAULT 0,
                category TEXT DEFAULT 'Другие комплектующие', brand TEXT DEFAULT '',
                model TEXT DEFAULT '', engine TEXT DEFAULT '', body_type TEXT DEFAULT '',
                part_number TEXT DEFAULT '', cross_numbers TEXT DEFAULT '',
                images TEXT DEFAULT '', quantity_available INTEGER DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        
        # Администраторы
        conn.execute("""
            CREATE TABLE IF NOT EXISTS admins (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL
            )
        """)

        # Настройки сайта
        conn.execute("""
            CREATE TABLE IF NOT EXISTS site_settings (
                key TEXT PRIMARY KEY, value TEXT NOT NULL
            )
        """)
        
        defaults = {
            "phone": "+7 (951) 011-58-78", "address": "г. Владивосток, ул. Матросова, д. 30",
            "work_hours": "Пн-Пт: 10:00 - 18:00", "hero_title": "ТНВД. Без компромиссов."
        }
        for k, v in defaults.items():
            conn.execute("INSERT INTO site_settings (key, value) VALUES (%s, %s) ON CONFLICT DO NOTHING", (k, v))

        # Чаты
        conn.execute("""
            CREATE TABLE IF NOT EXISTS chat_messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id TEXT NOT NULL, sender TEXT NOT NULL, message TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        username = os.environ.get("ADMIN_USERNAME")
        password = os.environ.get("ADMIN_PASSWORD")
        if username and password:
            existing = conn.execute("SELECT id FROM admins WHERE username = %s", (username,)).fetchone()
            if not existing:
                conn.execute("INSERT INTO admins (username, password_hash) VALUES (%s, %s)",
                             (username, generate_password_hash(password)))
        conn.commit()


