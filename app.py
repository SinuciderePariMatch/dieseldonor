@app.route("/admin/chats")
@admin_required
def admin_chats():
    """Страница со списком всех активных диалогов"""
    with get_db() as conn:
        # Группируем по session_id, берем последнее сообщение и время
        chats = conn.execute("""
            SELECT 
                session_id,
                MAX(created_at) as last_msg_time,
                COUNT(*) as msg_count,
                (SELECT message FROM chat_messages cm2 
                 WHERE cm2.session_id = cm1.session_id 
                 ORDER BY cm2.created_at DESC LIMIT 1) as last_message,
                (SELECT sender FROM chat_messages cm3 
                 WHERE cm3.session_id = cm1.session_id 
                 ORDER BY cm3.created_at DESC LIMIT 1) as last_sender
            FROM chat_messages cm1
            GROUP BY session_id
            ORDER BY last_msg_time DESC
        """).fetchall()
        
    return render_template("admin_chats.html", chats=chats)


