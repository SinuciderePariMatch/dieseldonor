@app.route("/api/chat/save", methods=["POST"])
def save_chat_message():
    """Сохраняет сообщение от клиента или менеджера"""
    data = request.get_json()
    session_id = data.get("session_id") # Уникальный ID сессии клиента
    sender = data.get("sender") # 'client' или 'manager'
    message = data.get("message")
    
    if not session_id or not message:
        return jsonify({"error": "Bad request"}), 400
        
    with get_db() as conn:
        # Создаем таблицу чатов, если нет
        conn.execute("""
            CREATE TABLE IF NOT EXISTS chat_messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id TEXT NOT NULL,
                sender TEXT NOT NULL,
                message TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        
        conn.execute(
            "INSERT INTO chat_messages (session_id, sender, message) VALUES (%s, %s, %s)",
            (session_id, sender, message)
        )
        conn.commit()
        
    return jsonify({"status": "ok"})


